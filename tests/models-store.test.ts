import { after, test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { NextRequest } from 'next/server';
import { db, getRunConnection, cancelRun, getRun } from '../src/lib/audit/store';
import { createConfiguredRun } from '../src/lib/models/run-config';
import { saveConnection, listSettings, getRuntime, deleteConnection, recordTest, setDefault } from '../src/lib/models/store';
import { encryptSecret, decryptSecret } from '../src/lib/models/crypto';
import { GET, POST } from '../src/app/api/models/route';
const directory = mkdtempSync(join(tmpdir(), 'repocare-models-'));
process.env.REPOCARE_DB_PATH = join(directory, 'test.sqlite');
delete process.env.REPOCARE_MASTER_KEY;
const input = { name: '测试连接', provider: 'custom', protocol: 'openai-completions', baseUrl: 'https://provider.example/v1', modelId: 'custom-alias', apiKey: 'test-key-must-stay-private', keyAction: 'replace', contextWindow: 128000, maxTokens: 4096 };
after(() => { db().close(); rmSync(directory, { recursive: true, force: true }); });

test('authenticated encryption binds secrets to context and rejects tampering', () => {
  const encrypted = encryptSecret('secret', 'owner-a');
  assert.equal(decryptSecret(encrypted, 'owner-a'), 'secret');
  assert.throws(() => decryptSecret(encrypted, 'owner-b'), /无法解密/);
  const parts = encrypted.split('.'); parts[2] = Buffer.alloc(16).toString('base64');
  assert.throws(() => decryptSecret(parts.join('.'), 'owner-a'), /无法解密/);
});
test('connections are isolated, encrypted, revision checked and never return keys', () => {
  const saved = saveConnection('owner-a', input);
  assert.equal(listSettings('owner-a').defaultId, saved.id);
  assert.equal(listSettings('owner-b').connections.length, 0);
  assert.throws(() => getRuntime('owner-b', saved.id), /不属于/);
  assert.throws(() => setDefault('owner-b', saved.id), /不属于/);
  assert.throws(() => saveConnection('owner-b', input, saved.id, saved.revision), /不属于/);
  assert.doesNotMatch(JSON.stringify(listSettings('owner-a')), /test-key|apiKey/);
  const stored = db().prepare('SELECT secret FROM model_connections WHERE id = ?').get(saved.id) as { secret: string };
  assert.ok(stored.secret.startsWith('v1.'));
  assert.ok(!stored.secret.includes(input.apiKey));
  const kept = saveConnection('owner-a', { ...input, name: '改名', apiKey: '', keyAction: 'keep' }, saved.id, saved.revision);
  assert.equal(getRuntime('owner-a', saved.id).apiKey, input.apiKey);
  assert.throws(() => saveConnection('owner-a', input, saved.id, saved.revision), /已在其他页面修改/);
  assert.throws(() => recordTest('owner-a', saved.id, saved.revision, { ok: true, message: 'old', latencyMs: 0 }), /配置已更新/);
  const clear = saveConnection('owner-a', { ...input, apiKey: '', keyAction: 'clear' }, saved.id, kept.revision);
  assert.equal(clear.hasKey, false);
  assert.equal(getRuntime('owner-a', saved.id).apiKey, '');
});
test('queued runs retain encrypted configuration after editing/deleting a connection and clean it on completion', () => {
  const saved = saveConnection('snapshot-owner', input);
  const run = createConfiguredRun('snapshot-owner', 'https://github.com/example/project');
  assert.equal(run.model?.revision, 1);
  assert.doesNotMatch(JSON.stringify(getRun(run.id)), /test-key|apiKey|provider.example/);
  const changed = saveConnection('snapshot-owner', { ...input, apiKey: 'replacement' }, saved.id, saved.revision);
  deleteConnection('snapshot-owner', saved.id, changed.revision);
  assert.equal(getRunConnection(run.id)?.apiKey, input.apiKey);
  assert.equal(getRunConnection(run.id)?.revision, 1);
  assert.equal(listSettings('snapshot-owner').defaultId, null);
  cancelRun(run.id);
  assert.equal(getRunConnection(run.id), null);
  assert.equal(db().prepare('SELECT * FROM audit_run_models WHERE run_id = ?').get(run.id), undefined);
});
test('model HTTP endpoints set HttpOnly session, reject cross-origin and prevent foreign edits', async () => {
  const first = await GET(new NextRequest('http://localhost/api/models'));
  const cookie = first.headers.get('set-cookie')!;
  assert.match(cookie, /httponly/i);
  const headers = { 'content-type': 'application/json', cookie: cookie.split(';')[0], origin: 'http://localhost' };
  const create = await POST(new NextRequest('http://localhost/api/models', { method: 'POST', headers, body: JSON.stringify({ action: 'save', input }) }));
  assert.equal(create.status, 200);
  const data = await create.json();
  assert.equal(data.connections.length, 1);
  assert.doesNotMatch(JSON.stringify(data), /test-key|apiKey/);
  const foreign = await POST(new NextRequest('http://localhost/api/models', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ action: 'delete', id: data.connections[0].id, revision: 1 }) }));
  assert.equal(foreign.status, 400);
  const cross = await POST(new NextRequest('http://localhost/api/models', { method: 'POST', headers: { ...headers, origin: 'https://attacker.example' }, body: JSON.stringify({ action: 'default', id: null }) }));
  assert.equal(cross.status, 400);
  const invalid = await POST(new NextRequest('http://localhost/api/models', { method: 'POST', headers, body: JSON.stringify({ action: 'save', input: { ...input, protocol: 'unknown' } }) }));
  assert.equal(invalid.status, 400);
});
